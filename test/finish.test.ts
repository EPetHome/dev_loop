  const f = await finishingFixture(t,{flow}), {dir,worktree} = f.task;
  f.git("init","--bare",join(f.base,"origin.git")); f.git("remote","add","origin",join(f.base,"origin.git")); f.git("push","origin","dev");
  await settle(dir);
  const events: Record<string,any> = {}, timers = new Map<number,()=>void>();
  registerPi({on:(name,handler)=>events[name]=handler,sendMessage:()=>{}},{env:{LOOP_TASK_DIR:dir},every:(cb,ms)=>timers.set(ms,cb),clear:()=>{}});
  events.session_start({}, {cwd:worktree,hasUI:false,sessionManager:{getSessionId:()=>"fake",getBranch:()=>[]}});
  const pulse = timers.get(60000)!, statusLock = join(dir,"status.lock");
  const before = statusOf(dir), unlock = lock(statusLock); let now = Date.now();
  const clock = t.mock.method(Date,"now",()=>now+=3000);
  try { assert.doesNotThrow(pulse); } finally { clock.mock.restore(); unlock(); }
  assert.deepEqual(statusOf(dir),before,"心跳遇到忙锁不抢写失败状态");

  const deletion = await gateRemoval(t,f,"收尾","after");
  const deleting = statusOf(dir); assert.equal(deleting.state,"completed"); assert.ok(deleting.loop.releasePending?.target);
  assert.ok(existsSync(join(dir,"operation.lock"))); lock(statusLock)(); pulse();
