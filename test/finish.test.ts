  assert.equal(receipt.loop.finisher,null); assert.match(receipt.message,/工作区已释放/);
  assert.match(readFileSync(join(f.repo,"结果.md"),"utf8"),/工作区已释放/);
  assert.deepEqual(received(dir).map(c=>c.name),["deploy","check"]);
  assert.equal(f.git("rev-parse","dev"),committed);
  assert.deepEqual(checksOf(dir).slice(0,-1),checks); assert.equal(checksOf(dir).at(-1)?.result,"已释放");
  assert.throws(()=>resume(dir),/已释放/);
